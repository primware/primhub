extension LocalizedString on String {
  String getStringWithVariables(BuildContext context, Map<String, String> variables) {
    var value = getString(context);
    for (final entry in variables.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value);
    }
    return value;
  }
}
